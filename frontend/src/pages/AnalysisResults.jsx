import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { 
  ArrowLeft, 
  Download, 
  Copy, 
  Check,
  CheckCircle2,
  Code2
} from 'lucide-react';
import { ScoreGauge } from '../components/ScoreGauge';
import { IssueCard } from '../components/IssueCard';
import { useAnalysis } from '../context/AnalysisContext';

export const AnalysisResults = () => {
  const navigate = useNavigate();
  const { currentResult } = useAnalysis();

  const [activeFilter, setActiveFilter] = useState('all');
  const [copiedSummary, setCopiedSummary] = useState(false);

  if (!currentResult) {
    return (
      <div className="dashboard-card" style={{ textAlign: 'center', padding: '60px 20px', maxWidth: '600px', margin: '40px auto' }}>
        <Code2 size={44} style={{ color: 'var(--accent-blue)', margin: '0 auto 16px' }} />
        <h2 style={{ fontSize: '20px', color: '#fff', marginBottom: '8px' }}>No Active Analysis Loaded</h2>
        <p style={{ color: 'var(--text-muted)', margin: '0 auto 24px', fontSize: '14px', maxWidth: '420px' }}>
          Select or paste source code into the Code Analyzer to execute real AST static analysis on the backend engine.
        </p>
        <button onClick={() => navigate('/analyzer')} className="btn btn-primary">
          Open Code Analyzer
        </button>
      </div>
    );
  }

  const {
    id,
    title,
    repo,
    branch,
    language,
    qualityScore = 100,
    grade = 'A+',
    verdict = 'Passed Quality Gate',
    duration = '0.35s',
    linesScanned = 0,
    summary = { critical: 0, warning: 0, info: 0, suggestion: 0 },
    issues = []
  } = currentResult;

  const suggestionsCount = summary.info ?? summary.suggestion ?? 0;

  const filteredIssues = issues.filter(issue => {
    if (activeFilter === 'all') return true;
    if (activeFilter === 'info' || activeFilter === 'suggestion') {
      return issue.severity?.toLowerCase() === 'info' || issue.severity?.toLowerCase() === 'suggestion';
    }
    return issue.severity?.toLowerCase() === activeFilter.toLowerCase();
  });

  const handleCopyPRComment = () => {
    const commentMarkdown = `## 🛡️ PR Sentinel Quality Report
**Target:** ${title} (${id})
**Overall Score:** ${qualityScore}/100 (${grade}) — **Verdict:** ${verdict}
- 🚨 **Critical Issues:** ${summary.critical}
- ⚠️ **Warnings:** ${summary.warning}
- ℹ️ **Suggestions:** ${suggestionsCount}

### Detected Findings (${issues.length}):
${issues.length === 0 ? '- *No static issues found. Code adheres to all active rules.*' : issues.map(i => `- **[Line ${i.line}] [${i.severity.toUpperCase()}]** ${i.title} (\`${i.ruleId}\`)\n  *Fix:* ${i.recommendedSolution || i.correctedCode || 'See dashboard report'}`).join('\n')}

*Generated by PR Sentinel AST Static Engine*`;

    navigator.clipboard.writeText(commentMarkdown);
    setCopiedSummary(true);
    setTimeout(() => setCopiedSummary(false), 2000);
  };

  const handleExportJSON = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(currentResult, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `pr-sentinel-${id}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  return (
    <div className="animate-fade-in">
      {/* Top action row */}
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '20px' }}>
        <button 
          onClick={() => navigate('/analyzer')} 
          className="btn btn-secondary btn-sm"
        >
          <ArrowLeft size={14} />
          <span>Back to Analyzer</span>
        </button>

        <div style={{ display: 'flex', gap: '10px' }}>
          <button 
            onClick={handleCopyPRComment} 
            className="btn btn-secondary btn-sm"
          >
            {copiedSummary ? <Check size={14} style={{ color: '#34d399' }} /> : <Copy size={14} />}
            <span>{copiedSummary ? 'PR Comment Copied!' : 'Copy PR Review Comment'}</span>
          </button>

          <button 
            onClick={handleExportJSON} 
            className="btn btn-secondary btn-sm"
          >
            <Download size={14} />
            <span>Export Report (JSON)</span>
          </button>
        </div>
      </div>

      {/* Main Results Score Banner */}
      <div className="results-header-banner glow-card">
        <div className="score-display-wrapper">
          <ScoreGauge score={qualityScore} grade={grade} size={100} />
          
          <div className="results-banner-info">
            <h2>{title}</h2>
            <div className="results-meta-pills" style={{ marginTop: '8px' }}>
              <span className="results-meta-pill">
                <strong>ID:</strong> {id}
              </span>
              <span className="results-meta-pill">•</span>
              <span className="results-meta-pill">
                <strong>Target:</strong> {repo || 'local'} / {branch || 'patch'}
              </span>
              <span className="results-meta-pill">•</span>
              <span className="results-meta-pill">
                <strong>Language:</strong> {language}
              </span>
              <span className="results-meta-pill">•</span>
              <span className="results-meta-pill">
                <strong>Scanned:</strong> {linesScanned} lines in {duration}
              </span>
            </div>

            <div style={{ marginTop: '12px' }}>
              <span className={`badge ${qualityScore >= 85 ? 'badge-success' : qualityScore >= 70 ? 'badge-warning' : 'badge-critical'}`}>
                {verdict}
              </span>
            </div>
          </div>
        </div>

        {/* Severity Summary Quick Counter */}
        <div style={{ display: 'flex', gap: '14px', alignItems: 'center' }}>
          <div style={{ textAlign: 'center', padding: '10px 16px', background: 'rgba(244, 63, 94, 0.1)', border: '1px solid rgba(244, 63, 94, 0.25)', borderRadius: '10px' }}>
            <div style={{ fontSize: '22px', fontWeight: 800, color: '#fb7185', fontFamily: 'var(--font-mono)' }}>
              {summary.critical || 0}
            </div>
            <div style={{ fontSize: '11px', color: 'var(--text-dim)', textTransform: 'uppercase', fontWeight: 700 }}>
              Critical
            </div>
          </div>

          <div style={{ textAlign: 'center', padding: '10px 16px', background: 'rgba(245, 158, 11, 0.1)', border: '1px solid rgba(245, 158, 11, 0.25)', borderRadius: '10px' }}>
            <div style={{ fontSize: '22px', fontWeight: 800, color: '#fbbf24', fontFamily: 'var(--font-mono)' }}>
              {summary.warning || 0}
            </div>
            <div style={{ fontSize: '11px', color: 'var(--text-dim)', textTransform: 'uppercase', fontWeight: 700 }}>
              Warnings
            </div>
          </div>

          <div style={{ textAlign: 'center', padding: '10px 16px', background: 'rgba(14, 165, 233, 0.1)', border: '1px solid rgba(14, 165, 233, 0.25)', borderRadius: '10px' }}>
            <div style={{ fontSize: '22px', fontWeight: 800, color: '#38bdf8', fontFamily: 'var(--font-mono)' }}>
              {suggestionsCount}
            </div>
            <div style={{ fontSize: '11px', color: 'var(--text-dim)', textTransform: 'uppercase', fontWeight: 700 }}>
              Suggestions
            </div>
          </div>
        </div>
      </div>

      {/* Filter Tabs & Issues Section */}
      <div className="issues-filter-bar">
        <div className="filter-tab-group">
          <button 
            onClick={() => setActiveFilter('all')} 
            className={`filter-tab ${activeFilter === 'all' ? 'active' : ''}`}
          >
            All Findings ({issues.length})
          </button>
          <button 
            onClick={() => setActiveFilter('critical')} 
            className={`filter-tab ${activeFilter === 'critical' ? 'active' : ''}`}
          >
            Critical ({summary.critical || 0})
          </button>
          <button 
            onClick={() => setActiveFilter('warning')} 
            className={`filter-tab ${activeFilter === 'warning' ? 'active' : ''}`}
          >
            Warnings ({summary.warning || 0})
          </button>
          <button 
            onClick={() => setActiveFilter('info')} 
            className={`filter-tab ${activeFilter === 'info' ? 'active' : ''}`}
          >
            Suggestions ({suggestionsCount})
          </button>
        </div>

        <span style={{ fontSize: '13px', color: 'var(--text-dim)' }}>
          Showing {filteredIssues.length} of {issues.length} detected findings
        </span>
      </div>

      {/* Issues Stack */}
      {filteredIssues.length === 0 ? (
        <div className="dashboard-card" style={{ textAlign: 'center', padding: '48px 24px' }}>
          <CheckCircle2 size={40} style={{ color: '#34d399', margin: '0 auto 12px' }} />
          <h3 style={{ fontSize: '18px', color: '#fff', marginBottom: '6px' }}>No issues found in this category</h3>
          <p style={{ color: 'var(--text-muted)', fontSize: '13px' }}>The submitted code passes all checks evaluated for this category.</p>
        </div>
      ) : (
        <div className="issues-stack">
          {filteredIssues.map((issue) => (
            <IssueCard key={issue.id} issue={issue} />
          ))}
        </div>
      )}
    </div>
  );
};
